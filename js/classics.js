// 網站所有取名用字與經文說明都出自這八部古籍：
//   古本易經      —— 六十四卦卦名、卦辭、大象傳（爻辭與彖傳未收）
//   古本紫微斗數  —— 十四主星、十二宮、四化
//   古本山海經    —— 山海、靈鳥異獸、草木、國族
//   古本神農本草  —— 《本草經》收載的藥名（不含功效敘述）
//   古本道德經    —— 八十一章中適合取名的句子
//   古本抱樸子    —— 內篇養生、德行相關的句子
//   古本詩經      —— 風、雅、頌
//   古本楚辭      —— 離騷、九歌、九章
//
// ── 三種資料層級，引用時必須分清楚 ────────────────────────
//
// 1. 經文（classical text）：易經卦辭與大象、詩經、楚辭、道德經、抱樸子。
//    這些是可以逐字查證的原文。tools/verify-quotes.cjs 會比對它們。
//
// 2. 名稱索引（index of names）：山海經篇目、本草藥名、紫微星名與宮名。
//    引用「山海經·桃林」指的是《山海經》的桃林條，不是引用某句經文。
//    本站在這些位置沒有原文，所以不列任何引文。
//
// 3. 現代描述（modern description）：紫微斗數的 note 欄
//    （「光明博愛」「印星忠良」）、神農本草曾經用過的 use 欄。
//    這些是現代命理與中藥學的用語，不是古籍原文。
//    紫微斗數尤其要說明：它是宋明時期成熟的命理系統，不是唐代古本，
//    這裡的 note 是現代人的描述，不是《紫微斗數全書》的引文。
//
// 資料定位：這是「取名用典」索引，用來標明每個字取自哪一部、哪一篇，
// 並非逐字訓詁或古籍校勘。五行歸屬沿用本站命名分類（部首與意象），
// 各姓名學派別有出入，不是唯一標準。

