export const HEXAGRAMS = Object.freeze(
  HEXAGRAM_ROWS.trim()
    .split('\n')
    .map((line) => {
      const [name, index, low, up, judgement, image] = line.split('|');
      const bits = TRIGRAM_BITS[low] + TRIGRAM_BITS[up];
      return Object.freeze({
        name,
        index: Number(index),
        low,
        up,
        judgement: judgement.trim(),
        image: image.trim(),
        // 由初爻到上爻，true 為少陽
        lines: bits.split('').map((bit) => bit === '1'),
        // 卦體五行取內卦（下卦）為本，沿用本站命名分類。
        // 這是描述卦象本身的屬性，不是給名字的建議 —— 名字一律取木、火。
        wx: TRIGRAMS[low].wx,
        glyph: TRIGRAMS[low].glyph + TRIGRAMS[up].glyph,
      });
    }),
);

// 依六爻查卦：初爻在上、兩兩成一組，先陽後陰
export const HEXAGRAM_BY_LINES = (() => {
  const map = new Map();
  for (const h of HEXAGRAMS) map.set(h.lines.map((y) => (y ? '1' : '0')).join(''), h);
  return map;
})();

